const has = (ings: Ingredient[], re: RegExp) => ings.some((i) => re.test(i.inci));
const hasFn = (ings: Ingredient[], fn: string) => ings.some((i) => i.fn.includes(fn as never));

function kindOf(r: Recipe, ings: Ingredient[]): Kind {
  const names = r.ingredients.map((i) => i.name.toLowerCase()).join(' ');
  if (/желток|авокадо|творог|йогурт|клубник|кефир|сок лука|мёд\b/.test(names) && r.shelfLife.includes('сразу')) return 'fresh';
  if (/глина|каолин/.test(names)) return 'clay';
  if (/соль|сода/.test(names) && !/вода дистил/.test(names)) return 'salt';
  if (/сахар|кофе молот|бамбук|скраб/.test(names + r.title.toLowerCase())) return 'scrub';
  if (hasFn(ings, 'surfactant')) return 'wash';
  if (hasFn(ings, 'emulsifier')) return 'emulsion';
  if (/воск|ши\b|какао/.test(names) && !/вода|гидролат/.test(names)) return 'balm';
  if (/камедь|целлюлоз|карбомер|гель/.test(names)) return 'gel';
  if (/вода|гидролат|алоэ/.test(names)) return 'water';
  return 'oil';
}

