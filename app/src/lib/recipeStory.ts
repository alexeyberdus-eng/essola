const cache = new Map<string, Story>();

export function recipeStory(r: Recipe): Story {
  const hit = cache.get(r.id);
  if (hit && !r.own) return hit;
  const pct = shares(r);
  const resolved = r.ingredients.map((i) => resolveIngredient(i.name));
  const ings = resolved.filter((x): x is Ingredient => !!x);
  const kind = kindOf(r, ings);

  const parts = r.ingredients.map((i, n) => {
    const ing = resolved[n];
    const share = pct && pct[n] > 0 ? formatPercent(pct[n]) : null;
    const named = BY_NAME.find(([re]) => re.test(i.name));
    if (named && (!ing || /бетаин кокамидопропил|консервант/i.test(i.name))) return { name: i.name, share, role: named[1], why: named[2] };
    if (!ing) return { name: i.name, share, role: 'Компонент', why: 'Отвечает за текстуру и характер средства.' };
    return { name: i.name, share, role: ing.fn.map((f) => FN_LABEL[f]).slice(0, 2).join(' · ') || 'Компонент', why: ing.about || ing.note };
  });

  const pairs = PAIRS.filter((p) => p.test(ings)).map(({ title, text }) => ({ title, text }));

  const balance: string[] = [];
  if (pct) {
    const sum = (re: RegExp) => r.ingredients.reduce((a, i, n) => (re.test(i.name.toLowerCase()) ? a + pct[n] : a), 0);
    const water = sum(/вода|гидролат|алоэ|отвар|настой/);
    const oils = sum(/масло|баттер|сквалан|ши\b|воск/);
    const actives = r.ingredients.reduce((a, i, n) => (resolved[n] && resolved[n]!.act >= 2 ? a + pct[n] : a), 0);
    if (water > 0) balance.push(`Вода и гидролаты — ${formatPercent(water)}: это лёгкая основа, которая доставляет увлажнение.`);
    if (oils > 0) balance.push(`Масла и баттеры — ${formatPercent(oils)}: они смягчают и «запечатывают» влагу. ${oils > 25 ? 'Это плотная питательная формула.' : oils > 10 ? 'Это сбалансированная текстура.' : 'Это лёгкая текстура, которая не оставляет блеска.'}`);
    if (actives > 0) balance.push(`Активы — ${formatPercent(actives)}. Это рабочие концентрации: достаточно для эффекта и без лишнего риска раздражения.`);
  }

  const storage = [
    `Срок: ${r.shelfLife || 'смотрите по рецепту'}.`,
    kind === 'fresh' || kind === 'clay' ? 'Готовьте на один раз и не храните.' : 'Храните в прохладе и темноте, набирайте средство чистым шпателем или сухими руками.',
    'Если изменились запах, цвет или текстура — средство пора выбросить.',
    'Перед первым применением сделайте тест на сгибе локтя и подождите сутки.',
  ];

  const lead = r.about || `${KIND_LEAD[kind]} ${r.subtitle ? `«${r.title}» — ${r.subtitle.toLowerCase()}.` : ''}`.trim();
  const story = { lead, parts, pairs, balance, technology: TECHNOLOGY[kind], equipment: EQUIPMENT[kind], storage };
  cache.set(r.id, story);
  return story;
}

/** Short teaser for cards: editorial text or the kind explanation. */
export const recipeTeaser = (r: Recipe) => recipeStory(r).lead;
