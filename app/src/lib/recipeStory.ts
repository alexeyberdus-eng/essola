/**
 * A long, readable explanation of a recipe, written from our ingredient base so every recipe gets one:
 * what the product is, what each component does, which pairings make it work, the technology behind
 * the steps, equipment and storage. Editorial text (recipe.about) leads when it exists.
 */
export type Story = {
  lead: string;
  parts: { name: string; share: string | null; role: string; why: string }[];
  pairs: { title: string; text: string }[];
  balance: string[];
  technology: string[];
  equipment: string[];
  storage: string[];
};

type Kind = 'emulsion' | 'gel' | 'oil' | 'balm' | 'wash' | 'clay' | 'scrub' | 'fresh' | 'salt' | 'water';

// Shares of the batch from amounts in g/ml; drops, "до pH" and "по вкусу" count as traces.
function shares(r: Recipe): number[] | null {
  const v = r.ingredients.map((i) => {
    const m = i.amount.trim().match(/^(\d+(?:[.,]\d+)?)\s*(г|мл)$/);
    return m ? parseFloat(m[1].replace(',', '.')) : 0;
  });
  const total = v.reduce((a, b) => a + b, 0);
  const known = v.filter((x) => x > 0).length;
  return total && known >= r.ingredients.length * 0.6 ? v.map((x) => (x / total) * 100) : null;
}

